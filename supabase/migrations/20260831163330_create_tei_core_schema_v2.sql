  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='people' and policyname='people_public_read') then
    create policy people_public_read on public.people for select using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='company_people' and policyname='company_people_public_read') then
    create policy company_people_public_read on public.company_people for select using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='evidence' and policyname='evidence_public_read') then
    create policy evidence_public_read on public.evidence for select using (true);
  end if;
end $$;;
